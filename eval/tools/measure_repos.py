"""Measure real scale of SCABench projects for Phase 3 cost planning.

Checks out every project with runner.checkout.checkout_project (so this also exercises it on real repos),
then counts what internal/tools/scan.py would send to the model, using scan.py's own EXT and filters.
No API calls. Run from eval/:  .venv\\Scripts\\python.exe tools\\measure_repos.py [--jobs 4] [--only id,id]
                               .venv\\Scripts\\python.exe tools\\measure_repos.py --selftest
"""
from __future__ import annotations

import argparse
import glob
import json
import os
import sys
import tempfile
from collections import Counter
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

EVAL = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(EVAL))
from runner.checkout import _long, checkout_project  # noqa: E402

DATASET = EVAL / "datasets/scabench/datasets/curated-2025-08-18/curated-2025-08-18.json"
SOURCES = EVAL / "datasets/sources"
OUT = EVAL / "measurements"

# Copied verbatim from internal/tools/scan.py (EXT dict keys). Re-check if scan.py changes.
SCAN_EXT = {".sol", ".ts", ".js", ".py", ".go"}
LANG = {".sol": "solidity", ".rs": "rust", ".move": "move", ".cairo": "cairo", ".vy": "vyper",
        ".ts": "ts/js", ".js": "ts/js", ".go": "go", ".py": "python"}
CONTRACT_LANGS = ("solidity", "rust", "move", "cairo", "vyper")
SKIP_DIRS = {".git", "node_modules", "lib"}  # for language and .sol stats
TEST_DIRS = {"test", "tests"}


def scanpy_files(root: str) -> list[str]:
    """Exactly scan.py's file selection (glob skips dot-entries; substring filters on the full path)."""
    return [p for p in glob.glob(os.path.join(root, "**", "*"), recursive=True)
            if os.path.splitext(p)[1] in SCAN_EXT
            and ".git" not in p.replace("\\", "/")
            and "node_modules" not in p.replace("\\", "/")
            and "/lib/" not in p.replace("\\", "/")]


def tree_stats(root: Path) -> dict:
    lang = Counter()
    sol_files = sol_lines = 0
    max_path = 0
    for dirpath, dirs, files in os.walk(_long(root)):
        rel_parts = Path(os.path.relpath(dirpath, _long(root))).parts
        if ".git" in dirs:
            dirs.remove(".git")
        for f in files:
            full = os.path.join(dirpath, f).removeprefix("\\\\?\\")
            max_path = max(max_path, len(full))
            if SKIP_DIRS & set(rel_parts):
                continue
            ext = os.path.splitext(f)[1]
            if ext in LANG:
                lang[LANG[ext]] += 1
            if ext == ".sol" and not f.endswith(".t.sol") and not TEST_DIRS & set(rel_parts):
                sol_files += 1
                with open(os.path.join(dirpath, f), "rb") as fh:
                    sol_lines += fh.read().count(b"\n")
    primary = lang.most_common(1)[0][0] if lang else None
    contract = {k: lang[k] for k in CONTRACT_LANGS if lang[k]}
    top_contract = max(contract, key=contract.get) if contract else None
    return {"primary_language": primary, "lang_file_counts": dict(lang),
            "primary_contract_language": top_contract,
            "in_segment_evm": top_contract == "solidity" and sol_files > 0,
            "sol_files": sol_files, "sol_lines": sol_lines, "max_abs_path_len": max_path}


def scan_stats(root: Path) -> dict:
    files = scanpy_files(str(root))
    real = [p for p in files if os.path.isfile(_long(Path(p)))]
    by_ext = Counter(os.path.splitext(p)[1] for p in real)
    tests = [p for p in real if p.endswith(".t.sol")
             or TEST_DIRS & set(Path(os.path.relpath(p, root)).parts[:-1])]
    return {"scanpy_files": len(real), "scanpy_glob_nonfile": len(files) - len(real),
            "scanpy_bytes": sum(os.path.getsize(_long(Path(p))) for p in real),
            "scanpy_by_ext": dict(by_ext), "scanpy_test_files": len(tests)}


def measure(project: dict) -> dict:
    r = checkout_project(project, SOURCES)
    row = {"project_id": project["project_id"], "checkout_status": r.status, "seconds": r.seconds,
           "unshallowed": r.unshallowed, "pinned": r.pinned, "head": r.head, "error": r.error,
           "codebases": len(project.get("codebases") or []),
           "truth_findings": len(project.get("vulnerabilities") or [])}
    if r.status == "ok":
        try:
            row |= tree_stats(r.path) | scan_stats(r.path)
        except Exception as e:  # measurement failure must not hide the checkout result
            row["error"] = f"measure failed: {type(e).__name__}: {e}"
    print(f"{row['project_id']}: {r.status} {r.seconds}s files={row.get('scanpy_files')}", flush=True)
    return row


def write_md(rows: list[dict], path: Path) -> None:
    ok = [r for r in rows if r["checkout_status"] == "ok" and "scanpy_files" in r]
    seg = [r for r in ok if r["in_segment_evm"]]
    L = ["# SCABench repo scale (Phase 3 cost planning)", "",
         "Generated by `eval/tools/measure_repos.py`. Checkout via `runner.checkout.checkout_project`.",
         "`scan.py files` uses scan.py's own selection: extensions .sol .ts .js .py .go, recursive glob "
         "(dot-files/dirs skipped), drop paths containing `.git`, `node_modules` or `/lib/`. "
         "Tests and scripts are NOT excluded by scan.py.",
         "`.sol` columns exclude lib/, node_modules/, .git/, test(s)/ and *.t.sol.", "",
         "| project | checkout | s | unshallow | lang | EVM | .sol | .sol lines | scan.py files (= calls) | of which tests | scan.py MB | max path |",
         "|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for r in rows:
        if "scanpy_files" not in r:
            L.append(f"| {r['project_id']} | {r['checkout_status']} | {r['seconds']} | {r['unshallowed']} |"
                     " - | - | - | - | - | - | - | - |")
            continue
        L.append(f"| {r['project_id']} | {r['checkout_status']} | {r['seconds']} | {r['unshallowed']} | "
                 f"{r['primary_contract_language'] or r['primary_language']} | {'yes' if r['in_segment_evm'] else 'NO'} | "
                 f"{r['sol_files']} | {r['sol_lines']} | {r['scanpy_files']} | {r['scanpy_test_files']} | "
                 f"{r['scanpy_bytes'] / 1e6:.2f} | {r['max_abs_path_len']} |")
    tot = sum(r["scanpy_files"] for r in ok)
    tot_seg = sum(r["scanpy_files"] for r in seg)
    L += ["", "## AttackTrail Claude call counts", "",
          "scan.py makes exactly one `messages.create` call per selected file (no batching, no retries; "
          "a failed call is logged and skipped). So calls per project = `scan.py files`.", "",
          f"- All {len(ok)} measured projects: **{tot} calls**, "
          f"{sum(r['scanpy_bytes'] for r in ok) / 1e6:.1f} MB of source sent.",
          f"- EVM segment only ({len(seg)} projects): **{tot_seg} calls**, "
          f"{sum(r['scanpy_bytes'] for r in seg) / 1e6:.1f} MB.",
          f"- Of all calls, {sum(r['scanpy_test_files'] for r in ok)} are test files and "
          f"{sum(r['scanpy_by_ext'].get(e, 0) for r in ok for e in ('.ts', '.js', '.py', '.go'))} are "
          ".ts/.js/.py/.go files (scripts, tests, tooling), which scan.py does not filter out.",
          "", "Per-extension totals: " + ", ".join(
              f"{e} {sum(r['scanpy_by_ext'].get(e, 0) for r in ok)}" for e in sorted(SCAN_EXT)), "",
          "No dollar cost is estimated here: there is no measured per-call cost (tokens in/out per call) "
          "for scan.py yet. Multiply these call counts by a measured per-call cost once one exists.", "",
          "## Projects outside the EVM segment", "",
          "scan.py has no .rs/.move/.cairo extension, so on these projects it sends few or no files that "
          "contain the audited code. Recall there would be artificially low and says nothing about the "
          "method; report them separately or exclude them.", ""]
    for r in ok:
        if not r["in_segment_evm"]:
            L.append(f"- `{r['project_id']}`: contract language {r['primary_contract_language']}, "
                     f"file counts {r['lang_file_counts']}; scan.py would send {r['scanpy_files']} files "
                     f"{r['scanpy_by_ext']}.")
    fails = [r for r in rows if r["checkout_status"] != "ok" or r.get("error")]
    L += ["", "## Checkout / measurement failures", ""]
    if not fails:
        L.append("None.")
    for r in fails:
        L += [f"### {r['project_id']} ({r['checkout_status']})", "", "```", str(r["error"]), "```", ""]
    unpinned = [r["project_id"] for r in rows if not r["pinned"]]
    if unpinned:
        L += ["", "## Not reproducible: dataset commit is a branch name", "",
              *[f"- `{p}`" for p in unpinned]]
    path.write_text("\n".join(L) + "\n", encoding="utf-8")


def selftest() -> None:
    with tempfile.TemporaryDirectory() as d:
        root = Path(d)
        for rel in ["src/A.sol", "src/B.t.sol", "test/C.sol", "lib/x/D.sol", "node_modules/E.js",
                    ".github/F.ts", "script/G.ts", "src/H.rs", "src/I.md"]:
            (root / rel).parent.mkdir(parents=True, exist_ok=True)
            (root / rel).write_text("a\nb\n", encoding="utf-8")
        t, s = tree_stats(root), scan_stats(root)
        assert (t["sol_files"], t["sol_lines"], t["in_segment_evm"]) == (1, 2, True), t
        # scan.py keeps A, B.t.sol, test/C, script/G; drops lib/, node_modules, dot-dir, .rs, .md
        assert (s["scanpy_files"], s["scanpy_test_files"]) == (4, 2), s
    print("selftest OK")


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--jobs", type=int, default=4)
    ap.add_argument("--only", default="")
    ap.add_argument("--selftest", action="store_true")
    a = ap.parse_args()
    if a.selftest:
        return selftest()
    projects = json.loads(DATASET.read_text(encoding="utf-8"))
    if a.only:
        want = set(a.only.split(","))
        projects = [p for p in projects if p["project_id"] in want]
    with ThreadPoolExecutor(a.jobs) as ex:
        rows = list(ex.map(measure, projects))
    OUT.mkdir(exist_ok=True)
    (OUT / "repo-scale.json").write_text(json.dumps(rows, indent=2, ensure_ascii=False), encoding="utf-8")
    write_md(rows, OUT / "repo-scale.md")
    print(f"wrote {OUT / 'repo-scale.json'} and repo-scale.md")


if __name__ == "__main__":
    main()
